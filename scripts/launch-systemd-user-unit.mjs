/**
 * Render-only systemd --user service for an independently verified owner
 * checkout. No service installation, enable/start/stop, linger changes,
 * Git mutations, Docker execution or secret reads are permitted here.
 */
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { lstat, readFile, realpath } from 'node:fs/promises';
import { delimiter, dirname, isAbsolute, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SHA = /^[a-f0-9]{40}$/;
const VALID_PATH = /^\/[a-zA-Z0-9._/-]+$/;
const TRUSTED_ORIGINS = new Set([
  'https://github.com/sauron9521/gym-dev-hub.git',
  'git@github.com:sauron9521/gym-dev-hub.git',
]);
const VERSION = '12.18.0';

export function parseUnitArgs(args) {
  if (
    args.length !== 2 ||
    !['--check-only', '--print-unit'].includes(args[0]) ||
    !args[1].startsWith('--operator-checkout=')
  )
    throw new Error('Require exactly a read-only mode and owner checkout');
  const checkout = args[1].slice('--operator-checkout='.length);
  if (!validPath(checkout)) throw new Error('Owner checkout must be an unambiguous canonical path');
  return { mode: args[0], checkout };
}

function validPath(value) {
  return (
    typeof value === 'string' &&
    value.length <= 1024 &&
    VALID_PATH.test(value) &&
    isAbsolute(value) &&
    resolve(value) === value &&
    !value.includes('//') &&
    !value.includes('/./') &&
    !value.includes('/../')
  );
}
function git(root, args) {
  const result = spawnSync('git', ['--no-optional-locks', '-C', root, ...args], {
    encoding: 'utf8',
    timeout: 10_000,
    maxBuffer: 8192,
    env: {
      PATH: process.env.PATH ?? '',
      HOME: process.env.HOME ?? '',
      GIT_CONFIG_NOSYSTEM: '1',
      GIT_CONFIG_GLOBAL: '/dev/null',
      GIT_OPTIONAL_LOCKS: '0',
      GIT_TERMINAL_PROMPT: '0',
    },
  });
  if (result.error || result.status !== 0) throw new Error('Owner Git metadata unavailable');
  return result.stdout.trim();
}

/** Static unit only: systemd user manager starts after login by default. */
export function renderUserUnit({ checkout, nodeBin, pnpmDir }) {
  if (![checkout, nodeBin, pnpmDir].every(validPath))
    throw new Error('Unsafe systemd unit path; no unit emitted');
  const executable = join(checkout, 'scripts/dev-operator.mjs');
  const paths = [...new Set([dirname(nodeBin), pnpmDir, '/usr/local/bin', '/usr/bin', '/bin'])];
  return [
    '# Generated by scripts/launch-systemd-user-unit.mjs; review before installing.',
    '# Owner-managed user unit: NOT installed, enabled or started by this generator.',
    '[Unit]',
    'Description=Gym Dev Hub local operator (compiled API + Web HMR)',
    'Documentation=https://github.com/sauron9521/gym-dev-hub',
    'StartLimitIntervalSec=600',
    'StartLimitBurst=2',
    '',
    '[Service]',
    'Type=exec',
    'WorkingDirectory=' + checkout,
    'ExecStart=' + nodeBin + ' ' + executable,
    'Environment="PATH=' + paths.join(':') + '"',
    'Environment="DOCKER_HOST=unix:///var/run/docker.sock"',
    'Environment="DOCKER_CONTEXT=default"',
    'UMask=0077',
    'NoNewPrivileges=true',
    'KillMode=control-group',
    'KillSignal=SIGTERM',
    'TimeoutStopSec=12s',
    'Restart=on-failure',
    'RestartSec=45s',
    '',
    '[Install]',
    'WantedBy=default.target',
    '',
  ].join('\n');
}
function run(command, args, cwd) {
  const r = spawnSync(command, args, {
    cwd,
    encoding: 'utf8',
    timeout: 15_000,
    maxBuffer: 8192,
    env: { PATH: process.env.PATH ?? '', HOME: process.env.HOME ?? '' },
  });
  if (r.error || r.status !== 0) throw new Error('Host dependency verification failed');
  return r.stdout.trim();
}
export async function verifyUnitInput(
  checkout,
  { nodeBin = process.execPath, pnpmBin = null } = {},
) {
  if (
    process.platform !== 'linux' ||
    process.getuid?.() === 0 ||
    Number(process.versions.node.split('.')[0]) < 24 ||
    !validPath(checkout) ||
    !validPath(nodeBin) ||
    (await realpath(checkout)) !== checkout
  )
    throw new Error('Non-root Linux Node 24+ with canonical checkout required');
  const root = await lstat(checkout);
  const gitDir = await lstat(join(checkout, '.git'));
  if (
    !root.isDirectory() ||
    root.isSymbolicLink() ||
    root.uid !== process.getuid() ||
    !gitDir.isDirectory() ||
    gitDir.isSymbolicLink() ||
    git(checkout, ['rev-parse', '--show-toplevel']) !== checkout ||
    git(checkout, ['symbolic-ref', '--short', 'HEAD']) !== 'main' ||
    !SHA.test(git(checkout, ['rev-parse', 'HEAD'])) ||
    !TRUSTED_ORIGINS.has(git(checkout, ['remote', 'get-url', 'origin']))
  )
    throw new Error('Expected current owner primary trusted main, not linked worktree');
  const script = await lstat(join(checkout, 'scripts/dev-operator.mjs'));
  if (!script.isFile() || script.isSymbolicLink() || script.size < 1)
    throw new Error('Verified operator entrypoint missing');
  const pkg = JSON.parse(await readFile(join(checkout, 'package.json'), 'utf8'));
  if (
    pkg.packageManager !== 'pnpm@' + VERSION ||
    pkg.scripts?.['dev:operator'] !== 'node scripts/dev-operator.mjs'
  )
    throw new Error('Unrecognized owner operator packageManager or launcher');
  const executable = await lstat(nodeBin);
  if (!executable.isFile() || executable.isSymbolicLink() || (executable.mode & 0o111) === 0)
    throw new Error('Absolute Node executable is not pinned and safe');
  const found = pnpmBin ?? run('/usr/bin/which', ['pnpm'], checkout);
  if (!validPath(found)) throw new Error('Unknown pinned pnpm location');
  if (run(found, ['--version'], checkout) !== VERSION) throw new Error('pnpm version mismatch');
  const unit = renderUserUnit({ checkout, nodeBin, pnpmDir: dirname(found) });
  return {
    status: 'read-only-user-unit-ready',
    unit,
    unitSha256: createHash('sha256').update(unit).digest('hex'),
    loginTargetAutostartPolicy: true,
    bootBeforeLoginRequestedByTool: false,
    existingServiceReplaced: false,
    systemdFilesWritten: false,
    userUnitEnabledByTool: false,
    servicesRestarted: false,
    existingOperatorStopped: false,
    lingerChanged: false,
  };
}
export async function main(args = process.argv.slice(2)) {
  const { mode, checkout } = parseUnitArgs(args);
  const result = await verifyUnitInput(checkout);
  if (mode === '--print-unit') process.stdout.write(result.unit);
  else {
    const { unit: omitted, ...report } = result;
    void omitted;
    process.stdout.write(JSON.stringify(report) + '\n');
  }
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(() => {
    process.stderr.write('SYSTEMD_USER_UNIT_REJECTED; review host and trusted owner checkout\n');
    process.exitCode = 2;
  });
}
